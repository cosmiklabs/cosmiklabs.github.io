import { mkdir, rm, cp, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const site=path.join(root,'site');
await rm(site,{recursive:true,force:true});await mkdir(site,{recursive:true});
await cp(path.join(root,'src/index.html'),path.join(site,'index.html'));
await cp(path.join(root,'assets'),path.join(site,'assets'),{recursive:true});
await writeFile(path.join(site,'robots.txt'),'User-agent: *\nDisallow: /\n');
console.log('Built private review preview in site/. No deployment configured.');
